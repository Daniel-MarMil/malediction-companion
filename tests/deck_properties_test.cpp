/// The maximum number of copies of a card for its rank in the test pack.
int limit_of(const Card& card) {
    const auto& limits = test_pack().deck_rules().copy_limits;
    const auto limit = limits.find(card.rank);
    return limit == limits.end() ? 0 : limit->second;
}

/// Cards that a deck for the Ash and Tide Seeker can include.
std::vector<const Card*> legal_for_dual_seeker() {
    const Card& seeker = *test_pack().find("T-SEEK-DUAL");
    std::vector<const Card*> result;
    for (const Card& card : test_pack().cards()) {
        const bool deck_type =
            card.type == CardType::Unit || card.type == CardType::Spell || card.type == CardType::Item;
        const bool fits =
            std::includes(seeker.sigils.begin(), seeker.sigils.end(), card.sigils.begin(), card.sigils.end());
        if (deck_type && limit_of(card) > 0 && fits) {
            result.push_back(&card);
        }
    }
    return result;
}

Deck dual_deck(std::vector<DeckEntry> main) {
    Deck deck;
    deck.seeker_id = "T-SEEK-DUAL";
    deck.legacy_id = "T-LEG-DUAL";
    deck.terrain_id = "T-TER-01";
    deck.main = std::move(main);
    return deck;
}

/// Shuffles the lines with keys generated by RapidCheck, so that the case can be replayed.
std::vector<DeckEntry> shuffled(std::vector<DeckEntry> lines) {
    const auto keys =
        *rc::gen::container<std::vector<std::uint32_t>>(lines.size(), rc::gen::arbitrary<std::uint32_t>());
    std::vector<std::size_t> order(lines.size());
    std::iota(order.begin(), order.end(), std::size_t{0});
    std::stable_sort(order.begin(), order.end(), [&](std::size_t a, std::size_t b) { return keys[a] < keys[b]; });
    std::vector<DeckEntry> result;
    result.reserve(lines.size());
    for (const std::size_t index : order) {
        result.push_back(std::move(lines[index]));
    }
    return result;
}

std::int64_t total_copies(const std::vector<DeckEntry>& lines) {
    std::int64_t total = 0;
    for (const auto& line : lines) {
        total += line.copies;
    }
    return total;
}

TEST(DeckProperties, LegalCardsOnlyFailOnSize) {
    const auto legal = legal_for_dual_seeker();
    ASSERT_GE(legal.size(), 20U);
    const bool ok = rc::check("a deck of legal cards within their limits only fails on size", [&] {
        std::vector<DeckEntry> lines;
        for (const Card* card : legal) {
            const int copies = *rc::gen::inRange(0, limit_of(*card) + 1);
            if (copies > 0) {
                lines.push_back({card->id, copies});
            }
        }
        const auto size = total_copies(lines);
        const auto issues = validate_deck(test_pack(), dual_deck(shuffled(std::move(lines))));
        for (const auto& issue : issues) {
            RC_ASSERT(issue.rule == Rule::DeckTooSmall || issue.rule == Rule::DeckTooLarge);
        }
        RC_ASSERT(issues.empty() == (size >= 30 && size <= 50));
    });
    EXPECT_TRUE(ok);
}

TEST(DeckProperties, OrderAndSplittingDoNotChangeTheResult) {
    std::vector<const Card*> all;
    for (const Card& card : test_pack().cards()) {
        all.push_back(&card);
    }
    const bool ok = rc::check("neither the order nor splitting the lines changes the issues", [&] {
        const auto picks = *rc::gen::container<std::vector<std::size_t>>(rc::gen::inRange<std::size_t>(0, all.size()));
        std::vector<DeckEntry> lines;
        std::vector<DeckEntry> split;
        for (const std::size_t pick : picks) {
            const int copies = *rc::gen::inRange(1, 5);
            lines.push_back({all[pick]->id, copies});
            for (int i = 0; i < copies; ++i) {
                split.push_back({all[pick]->id, 1});
            }
        }
        const auto original = validate_deck(test_pack(), dual_deck(lines));
        const auto rearranged = validate_deck(test_pack(), dual_deck(shuffled(std::move(split))));
        RC_ASSERT(rule_set(original) == rule_set(rearranged));
    });
    EXPECT_TRUE(ok);
}

TEST(DeckProperties, CardsThatShouldNotBeThereCountAndMarkTheDeck) {
    std::vector<std::string> ids;
    for (const Card& card : test_pack().cards()) {
        ids.push_back(card.id);
    }
    ids.emplace_back("NOT-IN-PACK");
    std::set<std::string> legal;
    for (const Card* card : legal_for_dual_seeker()) {
        legal.insert(card->id);
    }
    const bool ok = rc::check("cards that should not be in the deck count towards its size and mark it", [&] {
        const auto picks = *rc::gen::container<std::vector<std::size_t>>(rc::gen::inRange<std::size_t>(0, ids.size()));
        std::vector<DeckEntry> lines;
        std::int64_t invalid = 0;
        for (const std::size_t pick : picks) {
            const int copies = *rc::gen::inRange(1, 5);
            lines.push_back({ids[pick], copies});
            if (!legal.contains(ids[pick])) {
                invalid += copies;
            }
        }
        const auto size = total_copies(lines);
        const auto issues = validate_deck(test_pack(), dual_deck(std::move(lines)));
        RC_ASSERT(mc::test::has_issue(issues, Rule::DeckHasInvalidCards) == (invalid > 0));
        RC_ASSERT(mc::test::has_issue(issues, Rule::DeckTooSmall) == (size < 30));
        RC_ASSERT(mc::test::has_issue(issues, Rule::DeckTooLarge) == (size > 50));
    });
    EXPECT_TRUE(ok);
}

TEST(DeckProperties, WithoutAValidSeekerItIsTheOnlyIssue) {
    std::vector<std::string> ids;
    for (const Card& card : test_pack().cards()) {
        ids.push_back(card.id);
    }
    ids.emplace_back("NOT-IN-PACK");
    ids.emplace_back("");
    const bool ok = rc::check("without a valid Seeker, the Seeker is the only issue", [&] {
        const auto picks = *rc::gen::container<std::vector<std::size_t>>(rc::gen::inRange<std::size_t>(0, ids.size()));
        Deck deck = dual_deck({});
        for (const std::size_t pick : picks) {
            deck.main.push_back({ids[pick], *rc::gen::inRange(-1, 5)});
        }
        deck.seeker_id = *rc::gen::elementOf(ids);
        deck.legacy_id = *rc::gen::elementOf(ids);
        deck.terrain_id = *rc::gen::elementOf(ids);
        const Card* seeker = test_pack().find(deck.seeker_id);
        const bool valid_seeker = seeker != nullptr && seeker->type == CardType::Seeker;
        const auto issues = validate_deck(test_pack(), deck);
        if (valid_seeker) {
            RC_ASSERT(!mc::test::has_issue(issues, Rule::SeekerMissing));
            RC_ASSERT(!mc::test::has_issue(issues, Rule::SeekerInvalid));
        } else {
            RC_ASSERT(issues.size() == 1U);
            RC_ASSERT(issues.front().rule == (deck.seeker_id.empty() ? Rule::SeekerMissing : Rule::SeekerInvalid));
        }
    });
    EXPECT_TRUE(ok);
}

TEST(DeckProperties, ExceedingALimitIsAlwaysReported) {
    const auto legal = legal_for_dual_seeker();
    const bool ok = rc::check("going over the copy limit of a card is always detected", [&] {
        const Card* card = *rc::gen::elementOf(legal);
        const int copies = *rc::gen::inRange(limit_of(*card) + 1, 100);
        const bool in_side = *rc::gen::arbitrary<bool>();
        Deck deck = dual_deck({});
        auto& lines = in_side ? deck.side : deck.main;
        // The copies can be split between the main deck and the side deck: the limit is shared.
        const int first = *rc::gen::inRange(0, copies + 1);
        if (first > 0) {
            deck.main.push_back({card->id, first});
        }
        if (copies - first > 0) {
            lines.push_back({card->id, copies - first});
        }
        const auto issues = validate_deck(test_pack(), deck);
        RC_ASSERT(mc::test::has_issue(issues, Rule::TooManyCopies, card->id));
    });
    EXPECT_TRUE(ok);
}

TEST(DeckProperties, ValidationIsDeterministic) {
    std::vector<const Card*> all;
    for (const Card& card : test_pack().cards()) {
        all.push_back(&card);
    }
    const bool ok = rc::check("validating the same deck twice gives the same result", [&] {
        const auto picks = *rc::gen::container<std::vector<std::size_t>>(rc::gen::inRange<std::size_t>(0, all.size()));
        std::vector<DeckEntry> lines;
        for (const std::size_t pick : picks) {
            lines.push_back({all[pick]->id, *rc::gen::inRange(-1, 5)});
        }
        const Deck deck = dual_deck(std::move(lines));
        const auto first = validate_deck(test_pack(), deck);
        const auto second = validate_deck(test_pack(), deck);
        RC_ASSERT(first.size() == second.size());
        for (std::size_t i = 0; i < first.size(); ++i) {
            RC_ASSERT(first[i].rule == second[i].rule);
            RC_ASSERT(first[i].card_id == second[i].card_id);
            RC_ASSERT(first[i].detail == second[i].detail);
        }
    });
    EXPECT_TRUE(ok);
}

/// The lines of each card added together, in the place of the first one (what import gives).
std::vector<DeckEntry> merged(const std::vector<DeckEntry>& lines) {
    std::vector<DeckEntry> result;
    for (const DeckEntry& line : lines) {
        const auto found = std::find_if(result.begin(), result.end(),
                                        [&](const DeckEntry& entry) { return entry.card_id == line.card_id; });
        if (found == result.end()) {
            result.push_back(line);
        } else {
            found->copies += line.copies;
        }
    }
    return result;
}

/// Lines of random cards of the pack, of any type, whose merged copies stay within 1 to 99.
std::vector<DeckEntry> random_lines(const std::vector<const Card*>& all) {
    const auto picks = *rc::gen::container<std::vector<std::size_t>>(rc::gen::inRange<std::size_t>(0, all.size()));
    std::vector<DeckEntry> lines;
    std::map<std::string, int> totals;
    for (const std::size_t pick : picks) {
        const std::string& id = all[pick]->id;
        const int copies = *rc::gen::inRange(1, 100);
        if (totals[id] + copies <= max_deck_text_copies) {
            totals[id] += copies;
            lines.push_back({id, copies});
        }
    }
    return lines;
}

/// The id of a random card of that type, or none.
std::string maybe_card_of(CardType type) {
    std::vector<std::string> ids{""};
    for (const Card& card : test_pack().cards()) {
        if (card.type == type) {
            ids.push_back(card.id);
        }
    }
    return ids[*rc::gen::inRange<std::size_t>(0, ids.size())];
}

TEST(DeckProperties, ExportThenImportGivesTheSameDeck) {
    std::vector<const Card*> all;
    for (const Card& card : test_pack().cards()) {
        all.push_back(&card);
    }
    const bool ok = rc::check("importing an exported deck gives the same deck, with repeated lines merged", [&] {
        Deck deck;
        deck.seeker_id = maybe_card_of(CardType::Seeker);
        deck.legacy_id = maybe_card_of(CardType::Legacy);
        deck.terrain_id = maybe_card_of(CardType::Terrain);
        deck.main = random_lines(all);
        deck.side = random_lines(all);

        const std::string text = export_deck_text(test_pack(), deck);
        const ImportedDeck back = import_deck_text(test_pack(), text);
        RC_ASSERT(back.errors.empty());
        Deck expected = deck;
        expected.main = merged(deck.main);
        expected.side = merged(deck.side);
        RC_ASSERT(back.deck == expected);
        // Exporting what was imported writes the same text.
        RC_ASSERT(export_deck_text(test_pack(), back.deck) == text);
    });
    EXPECT_TRUE(ok);
}

